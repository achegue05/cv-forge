var idx = lang === "en" ? 1 : 0;

function t(key) {
  var v = S[key];
  if (!v) return key;
  return v[idx] !== undefined ? v[idx] : v[0];
}

CVF.i18n = {
  t: t,
  get lang() { return lang; },
  set: function (l) {
    lang = l === "en" ? "en" : "es";
    idx = lang === "en" ? 1 : 0;
    LS.set(LANG_KEY, lang);
    document.documentElement.setAttribute("lang", lang);
  },
  strings: S
};

